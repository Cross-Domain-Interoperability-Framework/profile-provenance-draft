#!/usr/bin/env python3
"""cdifProvToProvO.py - map a cdifProv record to PROV-O, qualified or plain.

Usage:
    python tools/cdifProvToProvO.py SRC.json OUT.ttl                 # PROV-O, qualified relations
    python tools/cdifProvToProvO.py SRC.json OUT.ttl --unqualified   # PROV-O, plain relations
    python tools/cdifProvToProvO.py --unqualify SRC.ttl OUT.ttl      # qualified PROV-O -> plain

The mapping (implementationTesting/MAPPING.md has the table):

- The record's root (the schema:Dataset) is a prov:Entity generated by each activity in its
  prov:wasGeneratedBy, at the activity's end time, except an activity whose result another listed
  activity takes as its schema:object: in a chain, only the last activity generates the root.
- An activity, and each step of an inline schema:actionProcess HowTo that is a schema:Action, is a
  prov:Activity; its schema:additionalType IRIs become rdf:type; schema:startTime / schema:endTime
  become prov:startedAtTime / prov:endedAtTime, and schema:location prov:atLocation (a prov:Location).
  A date with no time becomes midnight of that date, since PROV-O times are xsd:dateTime. The activity whose procedure a step is in lists
  the step in dcterms:hasPart, and the step keeps schema:position; the HowTo node itself has no PROV counterpart.
- schema:agent and schema:participant become a prov:qualifiedAssociation. The plan (the HowTo's
  schema:isBasedOn, or an actionProcess that is only an {@id}) is that association's prov:hadPlan,
  and a prov:Plan. A step with a plan (its own actionProcess) and no agent of its own is associated
  with its activity's agent, since a PROV-O association needs one. A schema:Role agent puts its contributor / agent / participant in prov:agent and
  its roleName in prov:hadRole (an IRI as it is; a DefinedTerm or string as a minted ex: role).
- schema:object becomes a prov:qualifiedUsage with prov:hadRole ex:InputData; a schema:instrument
  item becomes one with ex:Instrument, ex:Software or ex:Reagent, from its Wikidata kind term.
- schema:result becomes a prov:qualifiedGeneration at the activity's end time. A step's result that
  its activity also lists is the activity's: the step's generation is dropped, so the run, not its
  last step, generates the dataset (an entity gets one generation; the step is part of the run).
- Everything else is copied as it is: names, descriptions, versions, identifiers, schema:actionStatus
  (as an IRI), parameters (schema:additionalProperty), and the root's schema:subjectOf catalog record.
  PROV-O has no terms for them.

--unqualified (or --unqualify on a qualified Turtle) replaces each qualified relation by its plain
form and drops the qualification node: Usage -> prov:used, Association -> prov:wasAssociatedWith
(the plan and role are lost), Generation -> prov:wasGeneratedBy + prov:generatedAtTime, and the same
for Derivation, Invalidation, Attribution, Communication, Start, End and Delegation. Roles nothing
refers to any more are dropped.
"""
import argparse
import re
import sys

import rdflib
from rdflib import BNode, Literal, Namespace, URIRef
from rdflib.namespace import RDF, XSD

PROV = Namespace("http://www.w3.org/ns/prov#")
S = Namespace("http://schema.org/")
DCT = Namespace("http://purl.org/dc/terms/")
EX = Namespace("https://example.org/cdif-prov/")
WD = "https://www.wikidata.org/entity/"
KIND_ROLE = {WD + "Q3099911": EX.Instrument, WD + "Q7397": EX.Software, WD + "Q2356542": EX.Reagent}

# Properties the mapping turns into PROV; everything else on a mapped node is copied.
MAPPED = {S.additionalType, S.startTime, S.endTime, S.agent, S.participant, S.instrument,
          S.object, S.result, S.actionProcess, S.actionStatus, S.location, PROV.wasGeneratedBy, RDF.type}


class Mapper:
    def __init__(self, g):
        self.g, self.o = g, rdflib.Graph()
        for p, ns in g.namespaces():
            self.o.bind(p, ns, override=True)
        for p, ns in (("prov", PROV), ("schema", S), ("dcterms", DCT), ("xsd", XSD), ("ex", EX)):
            self.o.bind(p, ns, override=True, replace=True)
        self.copied, self.roles = set(), set()

    def copy(self, n, skip=()):
        """Copy n's triples (and its blank-node subtree) except the skipped properties."""
        if (n, tuple(skip)) in self.copied:
            return
        self.copied.add((n, tuple(skip)))
        for p, v in self.g.predicate_objects(n):
            if p in skip:
                continue
            self.o.add((n, p, v))
            if isinstance(v, BNode):
                self.copy(v)

    def dt(self, n, p):
        v = self.g.value(n, p)
        return None if v is None else Literal(str(v), datatype=XSD.dateTime)

    def entity(self, e):
        self.o.add((e, RDF.type, PROV.Entity))
        for t in self.g.objects(e, RDF.type):
            self.o.add((e, RDF.type, t))
        self.copy(e, skip={RDF.type})

    def usage(self, a, e, role):
        u = BNode()
        self.o.add((a, PROV.qualifiedUsage, u)); self.o.add((u, RDF.type, PROV.Usage))
        self.o.add((u, PROV.entity, e)); self.o.add((u, PROV.hadRole, role)); self.roles.add(role)

    def generation(self, e, a):
        q = BNode()
        self.o.add((e, PROV.qualifiedGeneration, q)); self.o.add((q, RDF.type, PROV.Generation))
        self.o.add((q, PROV.activity, a))
        t = self.dt(a, S.endTime)
        if t is not None:
            self.o.add((q, PROV.atTime, t))

    def role_of(self, r):
        rn = self.g.value(r, S.roleName)
        if isinstance(rn, URIRef):
            return rn
        name = self.g.value(rn, S.termCode) or self.g.value(rn, S.name) if isinstance(rn, BNode) else rn
        # "Hosting institution" -> ex:HostingInstitution; a camelCase termCode keeps its case
        return EX["".join(w[:1].upper() + w[1:] for w in re.split(r"\W+", str(name)))] if name else None

    def association(self, a, agent, plan):
        q = BNode()
        self.o.add((a, PROV.qualifiedAssociation, q)); self.o.add((q, RDF.type, PROV.Association))
        if (agent, RDF.type, S.Role) in self.g:
            role = self.role_of(agent)
            inner = next((self.g.value(agent, p) for p in (S.contributor, S.agent, S.participant)
                          if self.g.value(agent, p) is not None), None)
            if role is not None:
                self.o.add((q, PROV.hadRole, role)); self.roles.add(role)
            agent = inner
        self.o.add((q, PROV.agent, agent))
        types = set(self.g.objects(agent, RDF.type))
        self.o.add((agent, RDF.type, PROV.Person if S.Person in types else
                    PROV.Organization if S.Organization in types else PROV.Agent))
        self.copy(agent)
        if plan is not None:
            self.o.add((q, PROV.hadPlan, plan)); self.o.add((plan, RDF.type, PROV.Plan))
            self.o.add((plan, RDF.type, PROV.Entity))

    def activity(self, a, parent=None, inherited=(), claimed=frozenset()):
        g, o = self.g, self.o
        o.add((a, RDF.type, PROV.Activity))
        for t in g.objects(a, S.additionalType):
            if isinstance(t, URIRef):
                o.add((a, RDF.type, t))
        for src, dst in ((S.startTime, PROV.startedAtTime), (S.endTime, PROV.endedAtTime)):
            t = self.dt(a, src)
            if t is not None:
                o.add((a, dst, t))
        st = g.value(a, S.actionStatus)
        if st is not None:
            o.add((a, S.actionStatus, URIRef(str(st).replace("schema:", str(S)).replace("https://", "http://"))))
        if parent is not None:
            o.add((parent, DCT.hasPart, a))
        for loc in g.objects(a, S.location):
            o.add((a, PROV.atLocation, loc)); o.add((loc, RDF.type, PROV.Location)); self.copy(loc)
        self.copy(a, skip=MAPPED | {S.step})

        proc = g.value(a, S.actionProcess)
        steps = []
        plan = None
        if proc is not None:
            if (proc, RDF.type, S.HowTo) in g:
                plan = g.value(proc, S.isBasedOn)
                # only a step that is a schema:Action is an activity; a text-only HowToStep is lost
                steps = [s for s in g.objects(proc, S.step) if (s, RDF.type, S.Action) in g]
            else:
                plan = proc
        agents = list(g.objects(a, S.agent))
        if not agents and plan is not None:
            # a plan needs an agent in PROV-O: a step with none was carried out by its activity's agent
            agents = list(inherited)
        for ag in agents:
            self.association(a, ag, plan)
        for ag in g.objects(a, S.participant):
            self.association(a, ag, None)
        for e in g.objects(a, S.object):
            self.usage(a, e, EX.InputData); self.entity(e)
        for i in g.objects(a, S.instrument):
            kinds = {str(k) for k in g.objects(i, S.additionalType)}
            role = next((KIND_ROLE[k] for k in kinds if k in KIND_ROLE), EX.Instrument)
            self.usage(a, i, role); self.entity(i)
        # an enclosing activity that lists a result generates it (claimed); its step does not
        results = set(g.objects(a, S.result))
        for r in results:
            self.entity(r)
            if r not in claimed:
                self.generation(r, a)
        for s in steps:
            self.activity(s, parent=a, inherited=agents or inherited, claimed=claimed | results)

    def run(self):
        g = self.g
        for root in set(g.subjects(PROV.wasGeneratedBy, None)):
            acts = list(g.objects(root, PROV.wasGeneratedBy))
            used = {o for a in acts for o in g.objects(a, S.object)}
            self.entity(root)
            for rec in g.objects(root, S.subjectOf):  # the catalog record, metadata about the record
                self.copy(rec)
            self.o.remove((root, PROV.wasGeneratedBy, None))
            for act in acts:
                # in a chain, the root is generated by the last activity: one whose results no other
                # listed activity takes as input. The earlier ones lead to it through their inputs.
                # That activity generates the root, never one of its steps.
                last = not any(r in used for r in g.objects(act, S.result))
                if last:
                    self.generation(root, act)
                self.activity(act, claimed=frozenset({root}) if last else frozenset())
        for r in self.roles:
            self.o.add((r, RDF.type, PROV.Role))
        return self.o


PLAIN = {  # qualified property: (class, plain property, object property, time -> plain time property)
    PROV.qualifiedUsage: (PROV.used, PROV.entity, None),
    PROV.qualifiedAssociation: (PROV.wasAssociatedWith, PROV.agent, None),
    PROV.qualifiedGeneration: (PROV.wasGeneratedBy, PROV.activity, PROV.generatedAtTime),
    PROV.qualifiedDerivation: (PROV.wasDerivedFrom, PROV.entity, None),
    PROV.qualifiedInvalidation: (PROV.wasInvalidatedBy, PROV.activity, PROV.invalidatedAtTime),
    PROV.qualifiedAttribution: (PROV.wasAttributedTo, PROV.agent, None),
    PROV.qualifiedCommunication: (PROV.wasInformedBy, PROV.activity, None),
    PROV.qualifiedStart: (PROV.wasStartedBy, PROV.entity, None),
    PROV.qualifiedEnd: (PROV.wasEndedBy, PROV.entity, None),
    PROV.qualifiedDelegation: (PROV.actedOnBehalfOf, PROV.agent, None),
}


def unqualify(g):
    o = rdflib.Graph()
    for p, ns in g.namespaces():
        o.bind(p, ns, override=True)
    drop = set()
    for qp, (plain, obj, tprop) in PLAIN.items():
        for s, q in g.subject_objects(qp):
            drop.add(q)
            for v in g.objects(q, obj):
                o.add((s, plain, v))
            t = g.value(q, PROV.atTime)
            if tprop is not None and t is not None:
                o.add((s, tprop, t))
    for s, p, v in g:
        if s in drop or p in PLAIN:
            continue
        o.add((s, p, v))
    for r in set(o.subjects(RDF.type, PROV.Role)):
        if (None, PROV.hadRole, r) not in o and len(set(o.predicate_objects(r))) == 1:
            o.remove((r, None, None))
    return o


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("src"); ap.add_argument("out")
    ap.add_argument("--unqualified", action="store_true", help="write plain relations")
    ap.add_argument("--unqualify", action="store_true", help="SRC is qualified PROV-O Turtle")
    a = ap.parse_args(argv)
    if a.unqualify:
        out = unqualify(rdflib.Graph().parse(a.src, format="turtle"))
    else:
        out = Mapper(rdflib.Graph().parse(a.src, format="json-ld")).run()
        if a.unqualified:
            out = unqualify(out)
    out.serialize(a.out, format="turtle", encoding="utf-8")
    print(f"{a.out}: {len(out)} triples", file=sys.stderr)


if __name__ == "__main__":
    main()
